#!/usr/bin/env node
/**
 * Generates and bundles the local SQLite migrations for apps/mobile.
 *
 * `node scripts/rn/gen-migrations.mjs`
 *   1. runs `drizzle-kit generate` in apps/mobile against
 *      apps/mobile/src/data/db/schema.ts (fresh output directory),
 *   2. concatenates the generated SQL files in file-name order into
 *      apps/mobile/src/data/db/migrations.ts as
 *      `export const MIGRATIONS: readonly { id: string; sql: string }[]`,
 *      one entry per migration, `sql` holding that migration's statements
 *      (split on Drizzle's `--> statement-breakpoint`), each statement one
 *      array line — the generated file is never edited by hand.
 *
 * `node scripts/rn/gen-migrations.mjs --check`
 *   regenerates into a temporary directory, rebuilds the bundle in memory and
 *   exits 1 when the committed migrations.ts differs. The bundle content does
 *   not depend on drizzle-kit's random migration file names (ids are the
 *   zero-padded file-order index), so the check is deterministic.
 *
 * Edit src/data/db/schema.ts and re-run this script to change the schema.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const mobileDir = join(repoRoot, 'apps', 'mobile');
const schemaPath = join(mobileDir, 'src', 'data', 'db', 'schema.ts');
const bundlePath = join(mobileDir, 'src', 'data', 'db', 'migrations.ts');

const checkMode = process.argv.includes('--check');

const HEADER = `\
/**
 * GENERATED by scripts/rn/gen-migrations.mjs from src/data/db/schema.ts —
 * never edited by hand. Applied in order by src/data/db/client.ts; each
 * entry runs in one transaction, guarded by the database's user_version.
 */
export const MIGRATIONS: readonly { id: string; sql: readonly string[] }[] = [
`;

/** One Drizzle migration's SQL split into single statements. */
function statementsOf(sqlText) {
  return sqlText
    .split('--> statement-breakpoint')
    .map((statement) => statement.trim())
    .filter((statement) => statement.length > 0);
}

/** Runs drizzle-kit generate with a fresh out directory; returns that directory. */
function generate(outDir) {
  if (existsSync(outDir)) {
    rmSync(outDir, { recursive: true, force: true });
  }
  mkdirSync(outDir, { recursive: true });
  execFileSync(
    'npx',
    [
      'drizzle-kit',
      'generate',
      '--dialect',
      'sqlite',
      '--schema',
      schemaPath,
      '--out',
      outDir,
    ],
    { cwd: mobileDir, stdio: 'pipe' },
  );
  return outDir;
}

/** Builds the migrations.ts content from a drizzle-kit output directory. */
function buildBundle(outDir) {
  const sqlFiles = readdirSync(outDir)
    .filter((name) => name.endsWith('.sql'))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  if (sqlFiles.length === 0) {
    throw new Error(`no .sql migrations generated in ${outDir}`);
  }
  const entries = sqlFiles.map((file, index) => {
    const id = String(index).padStart(4, '0');
    const statements = statementsOf(readFileSync(join(outDir, file), 'utf8'));
    const lines = statements.map((statement) => `    \`${statement.replace(/\\/g, '\\\\').replace(/`/g, '\\`')}\`,`);
    return `  {\n    id: '${id}',\n    sql: [\n${lines.join('\n')}\n    ],\n  }`;
  });
  return `${HEADER}${entries.join(',\n')},\n];\n`;
}

const outDir = checkMode ? mkdtempSync(join(tmpdir(), 'coachcal-migrations-')) : join(mobileDir, 'src', 'data', 'db', 'migrations');

try {
  generate(outDir);
  const bundle = buildBundle(outDir);

  if (checkMode) {
    const committed = readFileSync(bundlePath, 'utf8');
    if (committed !== bundle) {
      console.error('gen-migrations: --check FAILED — src/data/db/schema.ts changed without regenerating.');
      console.error('Run: node scripts/rn/gen-migrations.mjs');
      process.exit(1);
    }
    console.log('gen-migrations: --check OK — migrations.ts matches the schema.');
  } else {
    mkdirSync(dirname(bundlePath), { recursive: true });
    writeFileSync(bundlePath, bundle);
    const sqlFiles = readdirSync(outDir).filter((name) => name.endsWith('.sql'));
    console.log(`gen-migrations: bundled ${sqlFiles.length} migration(s) into ${bundlePath.replace(repoRoot + '/', '')}`);
    for (const file of sqlFiles.sort()) {
      console.log(`  - ${file}`);
    }
  }
} finally {
  if (checkMode && existsSync(outDir)) {
    rmSync(outDir, { recursive: true, force: true });
  }
}
